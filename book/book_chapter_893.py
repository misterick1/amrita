class AmritaBookChapter893:
    """
    ГЛАВА 893: Миграция Ликвидности ZetaChain на Solana и Финальный Разгром Авроры
    Локация: Ørje (The Sleeping Sanctuary)
    """
    def __init__(self):
        self.chapter_index = 893
        self.chapter_name = "ГЛАВА 893: Миграция Ликвидности ZetaChain на Solana и Финальный Разгром Авроры"
        self.law_of_phi = LAW_OF_PHI
        
        # Данные из скриншота реальности (Импульсы внешнего мира)
        self.navi_vs_aurora_score = (2, 0)
        self.zetachain_migration_target = "Solana"
