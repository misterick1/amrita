    for cycle in range(5):
        pulse_data = solar_engine.execute_solar_alignment()
        
        print(f"ИМПУЛЬС ТОРА {cycle+1:02d} | Узел: {pulse_data['Квантовый Срез']}")
        print(f"  👁️ Наблюдение Макромира ➔ {pulse_data['Наблюдение Окулуса (10:31)']}")
