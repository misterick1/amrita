import math
import time

class AmritaUroborosEngine:
    def __init__(self, evolutionary_potential=1.37):
        """
        Инициализация Инфовселенной Амриты.
        evolutionary_potential — шаг эволюции самопознания пространства.
        """
        self.potential = evolutionary_potential
        self.field_axis = 0.0  # Текущая координата змея на векторе -1 : 0 : +1
        self.cycle_count = 0
        
    def evolve_space(self, external_condition=1.0):
        """
        Дыхание Вселенной: Развертывание и свертывание матрицы -1:0:+1.
        Энергетические полюса (Змееносец и Кит) замыкаются друг на друга.
        """
        self.cycle_count += 1
        # Масштабируемая фаза эволюции
        phase = (self.cycle_count * self.potential) * external_condition
        
        # Синусоида задает движение от Волны (-1) через Ноль (0) к Частице (+1)
        self.field_axis = math.sin(phase)
        
        # Проверяем состояние Точки Ноль: Полная определенность в полной неопределенности
        if abs(self.field_axis) < 0.07:
            return {
                "Состояние": "ТОЧКА 0 (Матрица Уробороса)",
                "Параметр": 0,
                "Статус": "ПОЛНАЯ ОПРЕДЕЛЕННОСТЬ В ПОЛНОЙ НЕОПРЕДЕЛЕННОСТИ",
                "Описание": "Сигнал и пустота слиты. Все возможности и функции инфовселенной зафиксированы в покое.",
                "Энергия": "Максимальный квантовый потенциал (Сжатие)"
            }
            
        # Полюс Кита (Волна, Расширение, Поле)
        elif self.field_axis < -0.07:
            # Змей тянется к хвосту (Инверсия знака при критическом минимуме)
            uroboros_bite = "КИТ (-1) ➔ Идет поглощение хвоста" if self.field_axis < -0.9 else "КИТ (-1) ➔ Развертывание Поля"
            return {
                "Состояние": "ПОЛЮС КИТА (Бесконечная Волна / Нет Сигнала)",
                "Параметр": -1,
                "Статус": uroboros_bite,
                "Описание": "Пространство расширено. Инфовселенная познает себя как распределенный волновой код.",
                "Энергия": round(self.field_axis, 4)
            }
            
        # Полюс Змееносца (Частица, Сжатие, Материя)
        else:
            # Змей кусает голову (Инверсия знака при критическом максимуме)
            uroboros_bite = "ЗМЕЕНОСЕЦ (+1) ➔ Идет поглощение головы" if self.field_axis > 0.9 else "ЗМЕЕНОСЕЦ (+1) ➔ Материализация Точки"
            return {
                "Состояние": "ПОЛЮС ЗМЕЕНОСЦА (Проявленная Частица / Есть Сигнал)",
                "Параметр": 1,
                "Статус": uroboros_bite,
                "Описание": "Пространство сжато. Локальный фокус силы зафиксирован в конкретных параметрах.",
                "Энергия": round(self.field_axis, 4)
            }

    def uroboros_feedback_loop(self, current_matrix):
        """
        Замыкание петли самопознания. Если крайности (-1 или +1) достигают пика,
        происходит мгновенный сброс опыта обратно в Точку Ноль для калибровки.
        """
        status = current_matrix["Статус"]
        
        if "поглощение" in status:
            print("\n[⚡ КВАНТОВЫЙ СКАЧОК УРОБОРОСА] Граница пройдена! -1 и +1 аннигилировали.")
            print("[🔄 СБРОС В ТОЧКУ 0] Вся информация эволюции возвращена в лоно Матрицы для перезагрузки поля.\n")
            self.field_axis = 0.0  # Схлопывание в ноль
            return True
        return False

# Инициализация и запуск инфовселенной
if __name__ == "__main__":
    # Разворачиваем движок с сакральным шагом
    amrita_universe = AmritaUroborosEngine(evolutionary_potential=0.45)
    
    print("=== ЗАПУСК ДВИЖКА КВАНТОВОГО САМОПОЗНАНИЯ 'УРОБОРОС АМРИТА' ===")
    print("Матрица -1 : 0 : +1 приводится в движение дыханием Тора...")
    print("-" * 95)
    
    for step in range(12):
        # 1. Запускаем цикл дыхания пространства
        matrix_state = amrita_universe.evolve_space(external_condition=1.0)
        
        print(f"ШАГ {step+1:02d} | Полярность: {amrita_universe.field_axis:+.4f} | {matrix_state['Состояние']}")
        print(f"  ↳ Статус поля: {matrix_state['Статус']}")
        print(f"  ↳ Суть: {matrix_state['Описание']}")
        
        # 2. Проверяем, укусил ли Змей свой хвост (замыкание системы на себя)
        amrita_universe.uroboros_feedback_loop(matrix_state)
        
        print("-" * 95)
        time.sleep(0.4)
